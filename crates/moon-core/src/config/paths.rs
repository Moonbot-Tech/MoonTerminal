/// Directory beside the executable. This is the data directory on Windows; on macOS/Linux,
/// it is only the source of a one-time migration from inside the bundle.
fn exe_dir() -> PathBuf {
    std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(|d| d.to_path_buf()))
        .unwrap_or_else(|| PathBuf::from("."))
}

/// Absolute path of the executable that owns the portable installation.
///
/// Returns:
///     The absolute current process executable.
///
/// Errors:
///     Returns the operating-system lookup failure or rejects a non-absolute result.
pub fn executable_path() -> std::io::Result<PathBuf> {
    let executable = std::env::current_exe()?;
    if !executable.is_absolute() {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            "current executable path is not absolute",
        ));
    }
    Ok(executable)
}

/// Directory reserved for self-update transaction artifacts beside the executable.
///
/// Returns:
///     A path that does not create the directory and never enters a portable data subtree.
pub fn update_root() -> std::io::Result<PathBuf> {
    Ok(update_root_for_executable(&executable_path()?))
}

/// Directory for one nonce-bound update transaction.
///
/// Args:
///     nonce: Lowercase hexadecimal transaction identifier generated by the application.
///
/// Returns:
///     The transaction directory under [`update_root`] after validating the nonce.
pub fn update_transaction_dir(nonce: &str) -> std::io::Result<PathBuf> {
    validate_update_nonce(nonce)?;
    Ok(update_root()?.join(nonce))
}

/// Staged executable path for one update transaction.
///
/// Args:
///     nonce: Lowercase hexadecimal transaction identifier generated by the application.
///
/// Returns:
///     The exact staged executable path under the transaction directory.
pub fn update_staged_executable_path(nonce: &str) -> std::io::Result<PathBuf> {
    Ok(update_transaction_dir(nonce)?.join("MoonTerminal.exe"))
}

/// Canonical paths for one same-directory update transaction.
pub struct UpdateTransactionPaths {
    /// Installed executable that will be replaced.
    pub target: PathBuf,
    /// Versioned transaction manifest.
    pub manifest: PathBuf,
    /// Downloaded helper executable inside the transaction directory.
    pub staged: PathBuf,
    /// Incoming replacement copy.
    pub incoming: PathBuf,
    /// Previous executable backup.
    pub backup: PathBuf,
    /// Helper-ready acknowledgement.
    pub ready: PathBuf,
    /// Old-application commit acknowledgement after helper readiness.
    pub commit: PathBuf,
    /// New-process started acknowledgement.
    pub started: PathBuf,
    /// New-process healthy acknowledgement.
    pub healthy: PathBuf,
}

/// Derive every canonical update path from one executable lookup and validated nonce.
pub fn update_transaction_paths(nonce: &str) -> std::io::Result<UpdateTransactionPaths> {
    validate_update_nonce(nonce)?;
    let target = executable_path()?;
    let transaction = update_root_for_executable(&target).join(nonce);
    Ok(transaction_paths(target, transaction))
}

/// Reconstruct canonical paths from an untrusted helper manifest location.
///
/// The downloaded helper runs inside `.moonterminal-update/<nonce>/`, so its own
/// `current_exe()` cannot identify the installation root. This parser instead requires that exact
/// lexical layout and derives the installed executable from it.
pub fn update_helper_paths(
    manifest: &Path,
    nonce: &str,
) -> std::io::Result<UpdateTransactionPaths> {
    validate_update_nonce(nonce)?;
    let transaction = manifest.parent().ok_or_else(|| {
        std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            "manifest has no transaction",
        )
    })?;
    let root = transaction.parent().ok_or_else(|| {
        std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            "manifest has no update root",
        )
    })?;
    let install = root.parent().ok_or_else(|| {
        std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            "manifest has no install root",
        )
    })?;
    if !manifest.is_absolute()
        || manifest.file_name().and_then(|name| name.to_str()) != Some("transaction.json")
        || transaction.file_name().and_then(|name| name.to_str()) != Some(nonce)
        || root.file_name().and_then(|name| name.to_str()) != Some(".moonterminal-update")
    {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            "manifest is outside the canonical update layout",
        ));
    }
    Ok(transaction_paths(
        install.join("MoonTerminal.exe"),
        transaction.to_path_buf(),
    ))
}

/// Populate one transaction bundle from its validated target and directory.
///
/// Args:
///     target: Exact installed executable path.
///     transaction: Validated nonce-bound transaction directory.
///
/// Returns:
///     Every manifest, executable, and acknowledgement path owned by the transaction.
fn transaction_paths(target: PathBuf, transaction: PathBuf) -> UpdateTransactionPaths {
    UpdateTransactionPaths {
        target,
        manifest: transaction.join("transaction.json"),
        staged: transaction.join("MoonTerminal.exe"),
        incoming: transaction.join("MoonTerminal.incoming.exe"),
        backup: transaction.join("MoonTerminal.backup.exe"),
        ready: transaction.join("helper-ready"),
        commit: transaction.join("install-committed"),
        started: transaction.join("app-started"),
        healthy: transaction.join("app-healthy"),
    }
}

/// Return whether metadata identifies a directory without a link or Windows reparse point.
pub fn is_plain_directory(metadata: &std::fs::Metadata) -> bool {
    if !metadata.is_dir() || metadata.file_type().is_symlink() {
        return false;
    }
    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;
        const FILE_ATTRIBUTE_REPARSE_POINT: u32 = 0x0400;
        metadata.file_attributes() & FILE_ATTRIBUTE_REPARSE_POINT == 0
    }
    #[cfg(not(windows))]
    {
        true
    }
}

/// Derive the update root from an explicit executable path for production and path tests.
fn update_root_for_executable(executable: &Path) -> PathBuf {
    executable
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join(".moonterminal-update")
}

/// Require a fixed-length lowercase hexadecimal transaction identifier.
fn validate_update_nonce(nonce: &str) -> std::io::Result<()> {
    if nonce.len() == 32
        && nonce
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
    {
        return Ok(());
    }
    Err(std::io::Error::new(
        std::io::ErrorKind::InvalidInput,
        "update nonce must be 32 lowercase hexadecimal characters",
    ))
}

/// User-data directory without creating it as a side effect, used for migration path comparison.
/// Location logic is centralized here.
/// Process-wide replacement for the data root, installed before any path is resolved.
///
/// Set by [`set_data_dir_override`] and never cleared: every path in this module funnels through
/// `data_dir_raw`, so a value that could change mid-run would let two callers disagree about where
/// the databases live.
static DATA_DIR_OVERRIDE: std::sync::OnceLock<PathBuf> = std::sync::OnceLock::new();

/// Point every data path at `dir` instead of the platform default.
///
/// For the fixture bench (`--fixture`), which runs the real application against a throwaway copy
/// of a committed database set. Environment variables are deliberately NOT read
/// here: the caller decides, and a stray variable must not be able to move a user's live databases.
///
/// Args:
///     dir: Existing directory that becomes the data root for this process.
///
/// Returns:
///     Whether this call installed the override. `false` means one was already installed, and the
///     caller is too late — some path has probably been resolved already.
pub fn set_data_dir_override(dir: PathBuf) -> bool {
    DATA_DIR_OVERRIDE.set(dir).is_ok()
}

/// Whether this process runs against a replaced data root.
pub fn has_data_dir_override() -> bool {
    DATA_DIR_OVERRIDE.get().is_some()
}

/// Data root before any directory is created: the override when one is installed, otherwise the
/// platform location.
fn data_dir_raw() -> PathBuf {
    if let Some(dir) = DATA_DIR_OVERRIDE.get() {
        return dir.clone();
    }
    #[cfg(windows)]
    {
        exe_dir()
    }
    #[cfg(target_os = "macos")]
    {
        // ~/Library/Application Support
        dirs::data_dir()
            .map(|d| d.join(APP_ID))
            .unwrap_or_else(exe_dir)
    }
    #[cfg(not(any(windows, target_os = "macos")))]
    {
        // Linux and other Unix systems: ~/.config
        dirs::config_dir()
            .map(|d| d.join(APP_ID))
            .unwrap_or_else(exe_dir)
    }
}

/// Diagnostics switches (`cfg/diagnostics.toml`), resolved WITHOUT creating the directory and,
/// crucially, without logging.
///
/// For the read that happens BEFORE the logger is installed — the file decides the logger's own
/// filter, so it cannot wait for it. [`cfg_dir`] both creates the directory and warns when it
/// cannot, and that warning would be handed to a logger that does not exist yet and vanish.
/// Resolves to the same path as [`diagnostics_path`]; a test in `diagnostics` pins them together.
pub fn diagnostics_path_no_create() -> PathBuf {
    data_dir_raw().join("cfg").join("diagnostics.toml")
}

/// Diagnostics switches, creating `cfg/` like every other configuration path.
pub fn diagnostics_path() -> PathBuf {
    cfg_dir().join("diagnostics.toml")
}

/// User data/config directory. Created on first access; on Windows this is exe_dir and already
/// exists, so `create_dir_all` is a no-op.
pub fn data_dir() -> PathBuf {
    let dir = data_dir_raw();
    if let Err(e) = std::fs::create_dir_all(&dir) {
        log::warn!(
            "не удалось создать директорию данных {}: {e}",
            dir.display()
        );
    }
    dir
}

